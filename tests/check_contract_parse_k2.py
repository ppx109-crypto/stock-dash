"""research/contract_parse_k2.py(공급계약 본문 칸 뽑기 판 k2) 합성 시험(네트워크 없음).

tests/check_dart_contracts.py는 수집 워크플로(dart-contracts.yml)의 push 트리거 경로라 건드리면 수집이 다시 돌아서,
k2 시험은 이 새 파일에 둠. k1(collect_dart_contracts.parse)이 같은 원문에서 틀리는 것도 함께 확인함.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "research"))
import collect_dart_contracts as k1  # noqa: E402
import collect_dart_customers as c  # noqa: E402
import contract_parse_k2 as k2  # noqa: E402

BR = '<br java="http://xml.apache.org/xalan/java">'


def td(*cells):
    return "<tr>" + "".join(f"<td><span>{x}</span></td>" for x in cells) + "</tr>"


def doc(*tables):
    return ("<html><head><STYLE>.xforms td { padding:0 }</STYLE></head><body>"
            + "".join(f"<table><tbody>{t}</tbody></table>" for t in tables) + "</body></html>").encode("utf-8")


BODY = (td("2. 계약내역", "계약금액(원)", "1,416,629,933,636") + td("최근매출액(원)", "2,792,736,856,185")
        + td("매출액대비(%)", "50.7") + td("3. 계약상대", "주식회사 디씨알이") + td("- 회사와의 관계", "-")
        + td("5. 계약기간", "시작일", "2020-04-13") + td("종료일", "-"))

# 1) 이상값 원문 줄 모양(012630 20250617800247과 같은 꼴): 정정표 한 칸에 이름 3줄 · 옆 칸에 정정전/정정후 값 2줄
FIX = (td("정정일자", "2025-06-17") + td("3. 정정사유", "변경계약 체결(계약금액 변경)") + td("4. 정정사항")
       + td("정정항목", "정정전", "정정후")
       + td(f"2. 계약내역 {BR}계약금액(원) {BR}매출액대비(%)", f"1,402,370,333,636 {BR}50.2", f"1,416,629,933,636 {BR}50.7"))
raw = doc(FIX, BODY)
old = k1.parse(c.lines_of(raw))
assert old["매출액대비%"] == "1402370333636", old  # k1은 % 칸에 정정전 금액을 잡음(고친 이유)
f, why = k2.parse_k2(raw, "정정")
assert f["매출액대비%"] == "50.7" and f["계약금액"] == "1416629933636" and f["최근매출액"] == "2792736856185", (f, why)
assert f["시작일"] == "2020-04-13" and f["종료일"] is None and why["종료일"].startswith("날짜 아님"), (f, why)
assert f["상대"] == "주식회사 디씨알이", f

# 2) 정정: 본문이 안 고쳐져 있어도 정정후 값 · 정정전 값은 절대 안 씀 · 종료일 범위 'a~b'는 b
stale = (td("확정 계약금액", "1,462,732,560") + td("조건부 계약금액", "-") + td("계약금액 총액(원)", "1,462,732,560")
         + td("최근 매출액(원)", "2,557,761,611") + td("매출액 대비(%)", "57.19") + td("3. 계약상대방", "가나다")
         + td("- 최근 매출액(원)", "999,999,999,999") + td("5. 계약기간", "시작일", "2025-04-11") + td("종료일", "2026-05-01"))
fix2 = (td("정정항목", "정정전", "정정후")
        + td(f"2. 계약내역{BR}- 확정 계약금액{BR}- 계약금액 총액(원){BR}- 매출액 대비(%)",
             f"1,462,732,560{BR}1,462,732,560{BR}57.19", f"- 1,496,201,019{BR}- 1,496,201,019{BR}- 58.50")
        + td("5. 계약기간 - 종료일", "2025.04.11~2026.05.01", "2025.04.11~2026.06.01")
        + td(f"3. 계약상대방{BR}- 최근 매출액(원){BR}- 주요사업", f"-{BR}-{BR}-", f"가나다{BR}7,191,805,311,000{BR}건설"))
f, why = k2.parse_k2(doc(fix2, stale), "정정")
assert f["계약금액"] == "1496201019" and f["매출액대비%"] == "58.50", (f, why)
assert f["종료일"] == "2026-06-01" and f["시작일"] == "2025-04-11", f
assert f["최근매출액"] == "2557761611", (f, why)  # 상대 회사 매출(정정표 3. 계약상대방 아래 · 본문 '- 최근 매출액')은 안 씀
assert "정정후" in why["계약금액"], why

# 3) 정정표 칸 이름이 틀린 원문(값이 % 이름 옆에 금액): 정정후 % 범위 밖 → 본문 % 사용
fix3 = (td("정정항목", "정정전", "정정후") + td("2. 계약내역 - 확정 계약금액", "6,462,000,000", "7,180,000,000")
        + td("2. 계약내역 - 매출액 대비(%)", "6,462,000,000", "7,180,000,000"))
body3 = (td("계약금액 총액(원)", "7,180,000,000") + td("최근 매출액(원)", "112,925,047,956") + td("매출액 대비(%)", "6.36"))
f, why = k2.parse_k2(doc(fix3, body3), "정정")
assert f["매출액대비%"] == "6.36" and "범위 밖" in why["매출액대비%"], (f, why)

# 4) % 범위 검사: 1000 넘어도 검산이 맞으면 둠(원문에 1,237.67 실제 있음) · 안 맞으면 None + 이유 · 음수 None
big = td("계약금액(원)", "8,526,224,000,000") + td("최근매출액(원)", "688,892,613,518") + td("매출액대비(%)", "1,237.67")
f, why = k2.parse_k2(doc(big))
assert f["매출액대비%"] == "1237.67" and "검산 맞음" in why["매출액대비%"], (f, why)
f, why = k2.parse_k2(doc(td("계약금액(원)", "100") + td("최근매출액(원)", "1,000") + td("매출액대비(%)", "1,300,000,000,000")))
assert f["매출액대비%"] is None and "범위 밖" in why["매출액대비%"], (f, why)
f, why = k2.parse_k2(doc(td("매출액대비(%)", "-4.8")))
assert f["매출액대비%"] is None and "음수" in why["매출액대비%"], (f, why)

# 5) 단위: 원 · 천원 · 백만원 · 억원 · 표 '단위' 표기 · 외화는 None
f, _ = k2.parse_k2(doc(td("계약금액(천원)", "12,345") + td("최근매출액(백만원)", "98,765") + td("매출액대비(%)", "12.5")))
assert f["계약금액"] == "12345000" and f["최근매출액"] == "98765000000", f
f, _ = k2.parse_k2(doc(td("(단위 : 백만원)") + td("계약금액", "1,500") + td("최근매출액", "3,000")))
assert f["계약금액"] == "1500000000" and f["최근매출액"] == "3000000000", f
f, _ = k2.parse_k2(doc(td("계약금액(억원)", "15.5")))
assert f["계약금액"] == "1550000000", f
f, why = k2.parse_k2(doc(td("계약금액(USD)", "1,000,000")))
assert f["계약금액"] is None and "단위" in why["계약금액"], (f, why)

# 6) 같은 행 바로 옆 칸만: 이름 칸 옆이 빈칸이면 다음 행 숫자를 끌어오지 않음 · 설명 문장 · '전체계약금액'은 이름 아님
f, why = k2.parse_k2(doc(td("계약금액(원)") + td("123,456") + td("- 본 공사의 전체계약금액", "219,291,115,000")))
assert f["계약금액"] is None and why["계약금액"] == "옆 칸 없음", (f, why)
f, why = k2.parse_k2(doc(td("계약금액(원)", f"147,646,816,100{BR}3.76")))
assert f["계약금액"] is None and why["계약금액"] == "한 칸에 값 여러 줄", (f, why)

# 7) 조건부 계약: '확정 계약금액'보다 '계약금액 총액' · 해지 공시는 해지금액 칸 따로
f, _ = k2.parse_k2(doc(td("확정 계약금액", "25,123,609,800") + td("조건부 계약금액", "1,744,066,200")
                       + td("계약금액 총액(원)", "26,867,676,000")))
assert f["계약금액"] == "26867676000", f
f, why = k2.parse_k2(doc(td("2. 해지내역", "해지금액(원)", "81,895,000,000") + td("최근매출액(원)", "431,722,625,741")
                         + td("매출액대비(%)", "18.97")), "해지")
assert f["해지금액"] == "81895000000" and f["계약금액"] is None and f["매출액대비%"] == "18.97", (f, why)

# 8) k1 합성 시험과 같은 원문(DART 표 꼴 TD) · 날짜 '.' → '-' · cp949 원문
xml = ("<TABLE><TR><TD>2. 계약내역</TD><TD>계약금액(원)</TD><TD>12,345,678,900</TD></TR>"
       "<TR><TD></TD><TD>최근 매출액(원)</TD><TD>98,765,432,100</TD></TR>"
       "<TR><TD></TD><TD>매출액 대비(%)</TD><TD>12.50</TD></TR>"
       "<TR><TD>3. 계약상대방</TD><TD>삼성전자(주)</TD></TR>"
       "<TR><TD>5. 계약기간</TD><TD>시작일</TD><TD>2024.01.02</TD></TR>"
       "<TR><TD></TD><TD>종료일</TD><TD>2024-12-31</TD></TR></TABLE>")
for enc in ("utf-8", "cp949"):
    f, why = k2.parse_k2(xml.encode(enc))
    assert f == {"계약금액": "12345678900", "최근매출액": "98765432100", "매출액대비%": "12.50", "시작일": "2024-01-02",
                 "종료일": "2024-12-31", "상대": "삼성전자(주)", "해지금액": None}, (enc, f, why)
f, why = k2.parse_k2(b"<P>no table</P>")
assert all(v is None for v in f.values()) and why["계약금액"] == "칸 이름 못 찾음", why
print("공급계약 k2 시험 통과")
